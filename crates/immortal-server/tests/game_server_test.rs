//! # Loopback Integration Tests for GameServer
//! Validates Tokio UdpSocket exchange, CPackUdp framing, UE3 bunch handshake,
//! actor channel replication, and graceful daemon shutdown.

use immortal_core::ChampionId;
use immortal_net::{
    Bunch, ControlMessage, HelloRecvReply, HelloSend, PingRecv, PingSend,
    ACTOR_CHANNEL_INDEX, CONTROL_CHANNEL_INDEX, CPACK_OP_BUNCH, DEFAULT_HMAC_KEY,
};
use immortal_server::{GameServer, GameServerConfig, ReplicationPayload};
use std::net::SocketAddr;
use std::time::Duration;
use tokio::net::UdpSocket;
use tokio::time::timeout;

#[tokio::test]
async fn test_game_server_loopback_integration() {
    // 1. Start server on dynamic loopback port
    let config = GameServerConfig {
        bind_addr: SocketAddr::from(([127, 0, 0, 1], 0)),
        ..Default::default()
    };
    let server_handle = GameServer::start(config).expect("Failed to start GameServer");
    let server_addr = server_handle.local_addr();

    // 2. Client loopback socket
    let client_socket = UdpSocket::bind("127.0.0.1:0")
        .await
        .expect("Failed to bind client UdpSocket");
    client_socket
        .connect(server_addr)
        .await
        .expect("Failed to connect client to GameServer");

    let mut buf = [0u8; 2048];

    // 3. Handshake Step 1: HelloSend -> HelloRecvReply
    let hello_bytes = HelloSend::build(DEFAULT_HMAC_KEY, 1337, None, 650);
    client_socket
        .send(&hello_bytes)
        .await
        .expect("Failed to send HelloSend");

    let n = timeout(Duration::from_millis(500), client_socket.recv(&mut buf))
        .await
        .expect("Timeout waiting for HelloRecvReply")
        .expect("Recv error");
    let hello_reply = HelloRecvReply::decode(&buf[..n]).expect("Failed to decode HelloRecvReply");
    assert_eq!(hello_reply.negotiated_mtu, 1414);

    // 4. Handshake Step 2: PingSend -> PingRecv
    let ping = PingSend::new(101, 55555, true);
    client_socket
        .send(&ping.encode())
        .await
        .expect("Failed to send PingSend");

    let n = timeout(Duration::from_millis(500), client_socket.recv(&mut buf))
        .await
        .expect("Timeout waiting for PingRecv")
        .expect("Recv error");
    let ping_reply = PingRecv::decode(&buf[..n]).expect("Failed to decode PingRecv");
    assert_eq!(ping_reply.sequence, 101);
    assert_eq!(ping_reply.client_timestamp, 55555);

    // 5. Handshake Step 3: Channel 0 NMT_Hello -> NetSpeed, Welcome, Ch2 Open, Spawn Fernando
    let nmt_hello = ControlMessage::Hello {
        engine_version: 10897,
        licensee_version: 0,
        map_url: "EntryMap".to_string(),
    };
    let hello_bunch = Bunch::control(0, nmt_hello.encode());
    client_socket
        .send(&hello_bunch.encode_cpack_udp())
        .await
        .expect("Failed to send NMT_Hello bunch");

    // Receive up to 5 bunches generated by handshake and actor spawn
    let mut received_bunches = Vec::new();
    for _ in 0..5 {
        match timeout(Duration::from_millis(200), client_socket.recv(&mut buf)).await {
            Ok(Ok(n)) => {
                let packet_bytes = &buf[..n];
                assert_eq!(packet_bytes[0], CPACK_OP_BUNCH, "Bunch datagram must have 0x04 prefix");
                let decoded = Bunch::decode_cpack_udp(packet_bytes).expect("Failed to decode bunch");
                received_bunches.push(decoded);
            }
            _ => break,
        }
    }

    assert!(
        received_bunches.len() >= 4,
        "Expected at least 4 bunches in response, got {}",
        received_bunches.len()
    );

    // Channel 0 Control sequence checks
    assert_eq!(received_bunches[0].header.ch_index, CONTROL_CHANNEL_INDEX);
    assert_eq!(received_bunches[0].header.ch_sequence, 0);

    assert_eq!(received_bunches[1].header.ch_index, CONTROL_CHANNEL_INDEX);
    assert_eq!(received_bunches[1].header.ch_sequence, 1);
    let welcome = ControlMessage::decode(&received_bunches[1].data).expect("Decode welcome");
    match welcome {
        ControlMessage::Welcome { level_url, .. } => {
            assert_eq!(level_url, "ShootingRange?game=ChaosGame.ChaosGameInfo");
        }
        other => panic!("Expected Welcome message, found {:?}", other),
    }

    // Channel 2 Actor sequence checks: must start at 0 independently
    assert_eq!(received_bunches[2].header.ch_index, ACTOR_CHANNEL_INDEX);
    assert_eq!(received_bunches[2].header.ch_sequence, 0);
    assert!(received_bunches[2].header.flags.b_open);

    // Fernando Pawn spawn on Channel 2 with sequence 1
    assert_eq!(received_bunches[3].header.ch_index, ACTOR_CHANNEL_INDEX);
    assert_eq!(received_bunches[3].header.ch_sequence, 1);
    let spawn_payload = ReplicationPayload::decode(&received_bunches[3].data).expect("Decode spawn");
    match spawn_payload {
        ReplicationPayload::SpawnActor {
            champion_id,
            class_name,
            location,
            ..
        } => {
            assert_eq!(champion_id, ChampionId::Fernando);
            assert_eq!(class_name, "TgPawn_Knight");
            assert_eq!(location.x, 0.0);
            assert_eq!(location.y, 0.0);
            assert_eq!(location.z, 100.0);
        }
        other => panic!("Expected SpawnActor, found {:?}", other),
    }

    // 6. Channel 2 Actor bunch roundtrip without wire protocol collision
    let actor_input = Bunch::actor(1, false, vec![0x03, 0x0A, 0x00, 0x00, 0x00]);
    client_socket
        .send(&actor_input.encode_cpack_udp())
        .await
        .expect("Failed to send actor input bunch");

    let n = timeout(Duration::from_millis(500), client_socket.recv(&mut buf))
        .await
        .expect("Timeout waiting for actor transform delta response")
        .expect("Recv error");
    assert_eq!(buf[0], CPACK_OP_BUNCH);
    let delta_bunch = Bunch::decode_cpack_udp(&buf[..n]).expect("Failed to decode delta bunch");
    assert_eq!(delta_bunch.header.ch_index, ACTOR_CHANNEL_INDEX);

    // 7. Graceful server shutdown
    server_handle
        .shutdown()
        .await
        .expect("Graceful shutdown must complete successfully");
}
